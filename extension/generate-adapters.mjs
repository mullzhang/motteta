import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { compileMatchPattern } from "./src/adapters/match-pattern.ts";

export const extensionRoot = dirname(fileURLToPath(import.meta.url));

function validateSettings(value, path) {
  const fields = ["anchorSelector", "id", "matches", "scope"];
  if (!value || typeof value !== "object" || Array.isArray(value) || Object.keys(value).sort().join() !== fields.join() ||
      typeof value.id !== "string" || !/^[a-z][a-z0-9-]*$/.test(value.id) ||
      typeof value.scope !== "string" || !value.scope.trim() ||
      typeof value.anchorSelector !== "string" || !value.anchorSelector.trim() ||
      !Array.isArray(value.matches) || !value.matches.length || !value.matches.every(p => typeof p === "string")) {
    throw new Error(`Invalid adapter settings: ${path}`);
  }
  for (const pattern of value.matches) compileMatchPattern(pattern);
  return value;
}

export async function discoverAdapters(root = extensionRoot) {
  const directory = join(root, "src/adapters/services");
  const names = (await readdir(directory, { withFileTypes: true })).filter(item => item.isDirectory()).map(item => item.name).sort();
  if (!names.length) throw new Error("At least one service adapter is required");
  const entries = [];
  const ids = new Set();
  for (const name of names) {
    const configPath = join(directory, name, "adapter.json");
    const settings = validateSettings(JSON.parse(await readFile(configPath, "utf8")), configPath);
    if (ids.has(settings.id)) throw new Error(`Duplicate adapter ID: ${settings.id}`);
    ids.add(settings.id);
    const handlerPath = join(directory, name, "adapter.ts");
    await access(handlerPath);
    entries.push({ settings, handlerPath });
  }
  return entries;
}

export function createManifest(base, adapters) {
  if ("host_permissions" in base || "content_scripts" in base) {
    throw new Error("Service permissions belong to adapter.json, not manifest.base.json");
  }
  const matches = [...new Set(adapters.flatMap(entry => entry.settings.matches))].sort();
  return {
    ...base,
    host_permissions: [...new Set(matches.map(pattern => compileMatchPattern(pattern).hostPermission))].sort(),
    content_scripts: [{ matches, js: ["content.js"], run_at: "document_idle" }],
  };
}

function registrySource(adapters, output) {
  const imports = adapters.map((entry, i) => {
    const path = relative(dirname(output), entry.handlerPath).split(sep).join("/");
    return `import handler${i} from ${JSON.stringify(path.replace(/\.ts$/, ""))};`;
  });
  const entries = adapters.map((entry, i) => `  { settings: ${JSON.stringify(entry.settings)}, handler: handler${i} },`);
  return ["// Generated by generate-adapters.mjs. Edit the service adapters, not this file.",
    'import type { ServiceAdapter } from "../adapters/types";', ...imports, "",
    "export const adapters: readonly ServiceAdapter[] = [", ...entries, "];", ""].join("\n");
}

export async function generateAdapters({ root = extensionRoot, check = false } = {}) {
  const adapters = await discoverAdapters(root);
  const base = JSON.parse(await readFile(join(root, "manifest.base.json"), "utf8"));
  const manifest = createManifest(base, adapters);
  const registry = join(root, "src/generated/adapters.ts");
  const outputs = [
    [registry, registrySource(adapters, registry)],
    [join(root, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n"],
  ];
  for (const [path, content] of outputs) {
    if (check) {
      if (await readFile(path, "utf8") !== content) throw new Error(`Generated adapter file is out of date: ${relative(root, path)}. Run npm run adapters.`);
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content);
    }
  }
  return { adapters, manifest };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  await generateAdapters({ check: Boolean(values.check) });
}
